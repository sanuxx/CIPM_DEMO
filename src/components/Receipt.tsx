import { Printer } from 'lucide-react'
import type { Payment } from '@/types'
import { useDB } from '@/store/db'
import { Button, Modal } from './ui'
import { Logo, PaymentBadge } from './common'
import { formatDateTime, formatLKR, formatLongDate } from '@/lib/utils'

export function ReceiptModal({ payment, onClose }: { payment: Payment | null; onClose: () => void }) {
  const db = useDB()
  const user = db.users.find((u) => u.id === payment?.userId)
  const course = db.courses.find((c) => c.id === payment?.courseId)
  const intake = db.intakes.find((i) => i.id === payment?.intakeId)
  return (
    <Modal
      open={!!payment} onOpenChange={(o) => !o && onClose()} title="Payment receipt" description="Simulated receipt — not a tax invoice" size="md"
      footer={<><Button variant="outline" onClick={() => window.print()}><Printer className="size-4" />Print</Button><Button onClick={onClose}>Close</Button></>}
    >
      {payment && user && (
        <div className="print-area rounded-xl border border-line p-6">
          <div className="flex items-start justify-between">
            <Logo />
            <div className="text-right text-xs text-muted"><p className="font-semibold text-ink">RECEIPT</p><p>{payment.reference}</p><p>{formatDateTime(payment.date)}</p></div>
          </div>
          <div className="mt-6 grid gap-4 text-sm sm:grid-cols-2">
            <div><p className="text-xs uppercase text-muted">Received from</p><p className="font-medium">{user.name}</p><p className="text-muted">{user.email}</p><p className="text-muted">{user.phone}</p>{user.studentNo && <p className="text-muted">{user.studentNo}</p>}</div>
            <div><p className="text-xs uppercase text-muted">Payment</p><p className="font-medium capitalize">{payment.method === 'card' ? `Card ending ${payment.cardLast4 ?? '••••'}` : 'Bank transfer'}</p><div className="mt-1"><PaymentBadge status={payment.status} /></div></div>
          </div>
          <table className="mt-6 w-full text-sm">
            <thead className="border-b border-line text-left text-xs uppercase text-muted"><tr><th className="py-2">Description</th><th className="py-2 text-right">Amount</th></tr></thead>
            <tbody>
              <tr className="border-b border-line"><td className="py-3"><p className="font-medium">{course?.title}</p><p className="text-xs text-muted">{intake?.name} · induction {intake ? formatLongDate(intake.date) : ''}</p></td><td className="py-3 text-right">{formatLKR(payment.amount)}</td></tr>
              <tr><td className="py-3 font-semibold">Total</td><td className="py-3 text-right text-base font-semibold">{formatLKR(payment.amount)}</td></tr>
            </tbody>
          </table>
          {payment.note && <p className="mt-2 text-xs text-muted">Note: {payment.note}</p>}
          <p className="mt-6 border-t border-line pt-3 text-center text-xs text-muted">Demo receipt generated by the eArrow LMS demo. No real payment was taken.</p>
        </div>
      )}
    </Modal>
  )
}
